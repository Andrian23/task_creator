export async function runAssistant(messages) {
  const apiKey = process.env.OPENAI_API_KEY;
  const localNow = new Date().toLocaleString('sv-SE', {
    timeZone: 'Asia/Bangkok',
    hour12: false,
  });

  const res = await fetch('https://api.openai.com/v1/chat/completions', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${apiKey}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      model: 'gpt-4o-mini',
      response_format: { type: 'json_object' },
      messages: [{
        role: 'system',
        content: `${SYSTEM_PROMPT}\n\nПоточні дата й час: ${localNow} (Asia/Bangkok, UTC+7).`,
      }, ...messages],
    }),
  });

  const data = await res.json();
  const content = data?.choices?.[0]?.message?.content;
  if (!content) {
    throw new Error(`OpenAI error: ${JSON.stringify(data)}`);
  }

  try {
    const result = JSON.parse(content);
    if (result.action === 'create' && !result.title_source) {
      return {
        action: 'ask',
        question: 'Як назвати таску? Можу взяти назву файла, ID/заголовок із матеріалу або твою назву.',
      };
    }
    if (result.action === 'create' && !result.due_datetime) {
      return { action: 'ask', question: 'На коли дедлайн?' };
    }
    return result;
  } catch {
    // Model didn't return valid JSON - ask the user to rephrase instead of crashing.
    return { action: 'ask', question: 'Не зрозумів, можеш переформулювати завдання?' };
  }
}
